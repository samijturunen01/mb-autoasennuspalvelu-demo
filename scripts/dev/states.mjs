// Captures interactive states for visual QA: mobile menu, form errors, van page, 404.
import { chromium } from '@playwright/test'
const [base, out] = process.argv.slice(2)
const browser = await chromium.launch()
const m = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 })
await m.goto(base + '/', { waitUntil: 'networkidle' })
await m.getByRole('button', { name: 'Valikko' }).click()
await m.waitForTimeout(300)
await m.screenshot({ path: `${out}/s-menu.png` })
await m.goto(base + '/yhteystiedot/', { waitUntil: 'networkidle' })
await m.getByLabel('Rekisterinumero').pressSequentially('kmp42')
await m.getByRole('button', { name: /Lähetä huoltoaikapyyntö/ }).click()
await m.waitForTimeout(300)
await m.screenshot({ path: `${out}/s-errors.png` })
const d = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await d.goto(base + '/pakettiautot/', { waitUntil: 'networkidle' })
await d.waitForTimeout(800)
await d.screenshot({ path: `${out}/s-vans.png` })
await d.goto(base + '/ei-ole/', { waitUntil: 'networkidle' })
await d.waitForTimeout(500)
await d.screenshot({ path: `${out}/s-404.png` })
await browser.close()
